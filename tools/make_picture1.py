# 导入必要的库
import matplotlib.pyplot as plt
import numpy as np

# ---------------------- 步骤1：准备完全随机分布的示例数据（第一象限内） ----------------------
# 生成完全随机的横坐标数据（100个样本，范围0-10）
x = np.random.uniform(0, 10, 100)
# 生成完全随机的纵坐标数据（100个样本，范围0-10，无任何线性趋势）
y = np.random.uniform(0.5, 10, 100)

# ---------------------- 步骤2：创建画布和坐标系 ----------------------
fig, ax = plt.subplots(figsize=(8, 6))  # figsize设置图表大小（宽, 高）

# ---------------------- 步骤3：绘制散点图（70个黑色，30个红色） ----------------------
# 方法1：拆分数据绘制（推荐，逻辑清晰）
# 前70个点保持黑色
ax.scatter(x[:70], y[:70], s=80, c='black', alpha=0.9)
# 后30个点设置为红色
ax.scatter(x[70:], y[70:], s=80, c='red', alpha=0.9)

# 方法2：使用颜色数组（可选，适合需要自定义更多颜色的场景）
# colors = ['black'] * 70 + ['red'] * 30
# ax.scatter(x, y, s=80, c=colors, alpha=0.9)

# ---------------------- 步骤4：调整刻度设置（移除所有刻度，包括纵坐标0刻度） ----------------------
# 横坐标：隐藏所有刻度
ax.set_xticks([])
ax.set_xticklabels([])
# 纵坐标：隐藏所有刻度（移除之前的0刻度，恢复无任何刻度的状态）
ax.set_yticks([])
ax.set_yticklabels([])

# ---------------------- 步骤5：关键修改1：仅保留第一象限的横纵坐标轴（无四周边框、无负向线） ----------------------
# 隐藏顶部、右侧边框，仅保留底部（x轴）和左侧（y轴）的坐标轴
ax.spines['top'].set_visible(False)
ax.spines['right'].set_visible(False)
# 调整坐标轴颜色和粗细，让线条更清晰
ax.spines['bottom'].set_color('black')
ax.spines['left'].set_color('black')
# 取消坐标轴0点交汇（恢复默认位置，仅显示第一象限的坐标轴线条）
# 注释掉之前的坐标轴位置调整代码，或直接删除，坐标轴默认位于图表边缘（对应第一象限的两条轴）

# ---------------------- 步骤6：关键修改2：给第一象限横纵坐标轴添加箭头（指向第一象限外侧） ----------------------
# 横轴（x轴，向右）添加箭头：在x轴最大值位置绘制向右箭头
x_max = ax.get_xlim()[1]  # 获取x轴当前最大值
ax.plot(x_max, 0, ">k", transform=ax.get_yaxis_transform(), clip_on=False)
# 纵轴（y轴，向上）添加箭头：在y轴最大值位置绘制向上箭头
y_max = ax.get_ylim()[1]  # 获取y轴当前最大值
ax.plot(0, y_max, "^k", transform=ax.get_xaxis_transform(), clip_on=False)

# ---------------------- 步骤7：确保不显示图例 ----------------------
ax.legend_.remove() if ax.legend_ else None  # 若存在图例则移除，无图例则不执行操作

# ---------------------- 步骤8：调整坐标范围（仅保留第一象限，无负向区间） ----------------------
ax.set_xlim(0, 11)  # x轴范围从0开始，无负值，对应第一象限横轴
ax.set_ylim(0, 11)  # y轴范围从0开始，无负值，对应第一象限纵轴

# ---------------------- 步骤9：显示图表 ----------------------
plt.show()